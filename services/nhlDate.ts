/**
 * NHL calendar dates are Eastern Time, not the device timezone.
 */

export function getNhlCalendarDate(now: Date = new Date()): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/New_York',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
}
